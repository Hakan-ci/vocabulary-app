// Generate the public row contract from the executable migrations, without live credentials.
import {database} from '../tests/dbHarness.mjs'
import {writeFile} from 'node:fs/promises'
const db=await database()
try {
 const {rows}=await db.query(`select table_name,column_name,data_type,udt_name,is_nullable,column_default from information_schema.columns where table_schema='public' order by table_name,ordinal_position`)
 const tables=new Map()
 for(const c of rows){if(!tables.has(c.table_name))tables.set(c.table_name,[]);tables.get(c.table_name).push(c)}
 const type=c=>({uuid:'string',text:'string',timestamptz:'string',date:'string',int4:'number',int8:'number',bool:'boolean',jsonb:'Json',_text:'string[]'}[c.udt_name]??'unknown')+(c.is_nullable==='YES'?' | null':'')
 let output="// Generated by npm run db:types from supabase/migrations. Do not edit manually.\nimport type { Json } from './models.ts'\nexport type Database = { public: { Tables: {\n"
 for(const [name,columns] of tables){output+=`  ${name}: {\n    Row: {\n`+columns.map(c=>`      ${c.column_name}: ${type(c)}`).join('\n')+'\n    }\n    Insert: {\n'+columns.map(c=>`      ${c.column_name}${c.is_nullable==='YES'||c.column_default!==null?'?':''}: ${type(c)}`).join('\n')+'\n    }\n    Update: {\n'+columns.map(c=>`      ${c.column_name}?: ${type(c)}`).join('\n')+'\n    }\n    Relationships: []\n  }\n'}
 output+=`}; Views: Record<string,never>; Functions: {
 kelime_snapshot_v2: { Args: Record<string,never>; Returns: Json }
 kelime_apply_v2: { Args: { p_operation: Json }; Returns: Json }
 kelime_snapshot_v3: { Args: Record<string,never>; Returns: Json }
 kelime_apply_v3: { Args: { p_operation: Json }; Returns: Json }
 kelime_snapshot: { Args: Record<string,never>; Returns: Json }
 kelime_apply: { Args: { p_operation: Json }; Returns: Json }
}; Enums: Record<string,never>; CompositeTypes: Record<string,never> } }\n`
 await writeFile(new URL('../src/data/database.types.ts',import.meta.url),output)
}finally{await db.close()}
